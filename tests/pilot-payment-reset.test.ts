import {test,expect,vi,afterEach} from 'vitest';
import {convexTest} from 'convex-test';
import {makeFunctionReference as ref} from 'convex/server';
import schema from '../convex/schema';
const modules=import.meta.glob('../convex/**/*.*s');
const R=(name:string)=>ref<any,any,any>(name);
afterEach(()=>vi.unstubAllEnvs());
test('scoped reset retains payment audit and other account, blocks old recovery and replay, permits fresh checkout',async()=>{
 vi.stubEnv('INTUNE_PILOT_MODE','v3');vi.stubEnv('PAYMENT_MODE','razorpay_test');
 const t=convexTest(schema,modules),phoneNumber='+12025550855';
 const token=await t.mutation(R('phoneUsers:getOrCreate'),{phoneNumber});
 const other=await t.mutation(R('phoneUsers:getOrCreate'),{phoneNumber:'+12025550856'});
 const order=await t.mutation(R('pilotPaymentsStore:reserveOrder'),{token,linkHash:'old-hash',checkoutToken:'old-token'});
 await t.mutation(R('pilotPaymentsStore:finishOrder'),{id:order.id,orderId:'order_fictionalReset'});
 const payment={id:'pay_fictionalReset',order_id:'order_fictionalReset',amount:9900,currency:'INR',status:'captured',captured:true};
 const g=await t.mutation(R('pilotPaymentsStore:confirm'),{id:order.id,payment});
 const otherGrant=await t.mutation(R('pilotAccess:grantTest'),{token:other,grantKey:'fictional-other'});
 await t.run(async c=>{const u=(await c.db.query('users').withIndex('by_token',q=>q.eq('token',token)).unique())!;await c.db.patch(u._id,{pilotStartedAt:Date.now(),pilotEndsAt:Date.now()+604800000,preferredName:'Fictional',conversationConsent:true});});
 const before=await t.run(c=>c.db.get(order.id));
 const reset=await t.mutation(R('pilotOperator:resetPaidAccess'),{phoneNumber,resetKey:'payment-reset:fictional-1'});
 expect(reset).toEqual({reset:true,revoked:1});expect((await t.query(R('pilotAccess:status'),{token})).state).toBe('unpaid');
 expect(await t.run(c=>c.db.get(order.id))).toEqual(before);
 expect((await t.query(R('pilotAccess:status'),{token:other})).id).toBe(otherGrant.id);
 expect(await t.query(R('pilotPaymentsStore:latestOrder'),{token})).toBeNull();
 await expect(t.query(R('pilotPaymentsStore:orderForLink'),{hash:'old-hash'})).rejects.toThrow('Checkout link unavailable');
 expect(await t.mutation(R('pilotPaymentsStore:confirm'),{id:order.id,payment,eventId:'fictional-delayed-event'})).toEqual(g);
 expect((await t.query(R('pilotAccess:status'),{token})).state).toBe('unpaid');
 expect(await t.mutation(R('pilotOperator:resetPaidAccess'),{phoneNumber,resetKey:'payment-reset:fictional-1'})).toEqual({reset:false,revoked:0});
 const fresh=await t.mutation(R('pilotPaymentsStore:reserveOrder'),{token,linkHash:'new-hash',checkoutToken:'new-token'});expect(fresh.id).not.toBe(order.id);
 await t.run(async c=>{const u=(await c.db.query('users').withIndex('by_token',q=>q.eq('token',token)).unique())!;expect(u.pilotStartedAt).toBeUndefined();expect(u.pilotEndsAt).toBeUndefined();expect(u.conversationConsent).toBe(true);});
});
test('unfinished checkout reset rejects atomically without revoking access',async()=>{
 vi.stubEnv('INTUNE_PILOT_MODE','v3');const t=convexTest(schema,modules),phoneNumber='+12025550857';
 const token=await t.mutation(R('phoneUsers:getOrCreate'),{phoneNumber});
 await t.mutation(R('pilotPaymentsStore:reserveOrder'),{token,linkHash:'unfinished'});
 await t.mutation(R('pilotAccess:grantTest'),{token,grantKey:'fictional-unfinished'});
 await expect(t.mutation(R('pilotOperator:resetPaidAccess'),{phoneNumber,resetKey:'payment-reset:fictional-2'})).rejects.toThrow('Unfinished checkout');
 expect((await t.query(R('pilotAccess:status'),{token})).state).toBe('eligible');
});
